"""WPS 文字题：按题库里的**完整原题**逐题写死的文档和检查点。

## 为什么要写死

通用规则（stem.py 的 parse_wps）是按题干句式猜的：引号里的原文抠出来塞进一篇
套话文章，格式要求拆成检查点。题干一复杂就露馅 —— 老师在机房查出来的：

- 「悯农」：题干说李绅那段是「李绅（772﹣846）……被誉为‘悯农诗人’。」，生成的
  文档里只有前半句，「被誉为」压根没有，学生找不到要改的那段；
- 「将文章最后一段（“‘谁知盘中餐……’……珍惜每一粒粮食。”）」—— 生成的文档里
  它根本不是最后一段，后半句「珍惜每一粒粮食」也没有；
- 「将文本框的高度设为 60 毫米」—— 文档里没有文本框，这一问谁也做不了，也没判。

题库里的 WPS 文字题就这十几道，每道题的文档该长什么样、每一问怎么判，照着原题
逐句写清楚，比让规则去猜靠谱得多。

## 每道题守的规矩

1. **题干引的每一段原文，文档里都完整存在**：开头、结尾和题干里省略号两边的字
   一字不差，而且独占一段；「最后一段」就真的是最后一段，「第 2 自然段」就真的是第 2 段。
2. **初始格式不能已经满足要求**：要设成黑体的先是宋体，要 B5 的先是 A4 —— 不然
   学生什么都不做也得分。
3. **题目要操作的对象都铺好**：文本框、图片、要替换的词、要移动的段落。
4. **每一问都有检查点**，一句话里要求几项就拆成几条，做对几项得几项的分。
   判不了的（比如图片「移到右侧」的精确位置）就判能判的那部分（锚在那一段旁边）。

## 怎么接进来

stem.parse_wps() 先按题干里的文件名查这张表，查到就用这里的，查不到才走通用规则。
库里存着旧规则生成的仿真任务的（恢复备份、导入旧数据包），由 stem.refresh_wps()
在出卷、判分时换成这里的 —— 老师在仿真器里手工改过的不动。
"""

from __future__ import annotations

from typing import List, Optional

from .sim import blank_para


def P(text: str, **fmt) -> dict:
    """一段：文字 + 初始格式（不写的项用默认：宋体、五号、左对齐）。"""
    return {**blank_para(), "text": text, **fmt}


def C(desc: str, score: int, **assertion) -> dict:
    """一条检查点。"""
    return {"desc": desc, "score": score, "assert": assertion}


def at(key: str) -> dict:
    """按内容找段落（学生前面插了段、挪了段，序号会变，内容不会）。"""
    return {"has": key}


